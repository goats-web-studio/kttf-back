-- Области — ADR-096.
--
-- Город лежит в области или ни в какой: Астана, Алматы и Шымкент — города
-- республиканского значения, в области не входят. Здесь заводятся 17 областей
-- Казахстана, по ним раскладываются областные центры, и добавляются 42 города
-- областного подчинения с координатами. Остальное администратор вносит
-- в «Местах».
--
-- Данные идут через поиск страны по коду и городов по названию: миграция
-- одинаково проходит и на пустом справочнике, и на демо-данных, и повторный
-- прогон заполнения ничего не задвоит.

-- CreateTable
CREATE TABLE "Region" (
    "id" TEXT NOT NULL,
    "countryId" TEXT NOT NULL,
    "name" TEXT NOT NULL,
    "nameKk" TEXT,
    "sortOrder" INTEGER NOT NULL DEFAULT 100,
    "isActive" BOOLEAN NOT NULL DEFAULT true,

    CONSTRAINT "Region_pkey" PRIMARY KEY ("id")
);

-- AlterTable
ALTER TABLE "City" ADD COLUMN "regionId" TEXT;

-- AlterTable
ALTER TABLE "ClubApplication" ADD COLUMN "cityId" TEXT;

-- CreateIndex
CREATE UNIQUE INDEX "Region_countryId_name_key" ON "Region"("countryId", "name");

-- CreateIndex
CREATE INDEX "City_regionId_idx" ON "City"("regionId");

-- AddForeignKey
ALTER TABLE "Region" ADD CONSTRAINT "Region_countryId_fkey" FOREIGN KEY ("countryId") REFERENCES "Country"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- AddForeignKey
ALTER TABLE "City" ADD CONSTRAINT "City_regionId_fkey" FOREIGN KEY ("regionId") REFERENCES "Region"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- AddForeignKey
ALTER TABLE "ClubApplication" ADD CONSTRAINT "ClubApplication_cityId_fkey" FOREIGN KEY ("cityId") REFERENCES "City"("id") ON DELETE SET NULL ON UPDATE CASCADE;

