-- Новые города. Центры уже есть — их эта вставка пропускает.
INSERT INTO "City" ("id", "countryId", "regionId", "name", "nameKk", "sortOrder", "lat", "lng")
SELECT gen_random_uuid()::text, country."id", region."id", town."name", town."nameKk", 100,
  town."lat", town."lng"
FROM "_RegionTown" town
JOIN "Country" country ON country."code" = 'KZ'
JOIN "Region" region ON region."countryId" = country."id" AND region."name" = town."region"
WHERE NOT EXISTS (
  SELECT 1 FROM "City" known
  WHERE known."countryId" = country."id" AND lower(known."name") = lower(town."name")
)
ON CONFLICT ("countryId", "name") DO NOTHING;

-- Уже заведённые города — центры и совпавшие по названию — встают в свою
-- область. Пустые казахское название и координаты дополняются, заполненные
-- администратором не трогаются.
UPDATE "City" city
SET "regionId" = region."id",
  "nameKk" = COALESCE(city."nameKk", town."nameKk"),
  "lat" = COALESCE(city."lat", town."lat"),
  "lng" = COALESCE(city."lng", town."lng")
FROM "_RegionTown" town, "Country" country, "Region" region
WHERE country."code" = 'KZ'
  AND region."countryId" = country."id"
  AND region."name" = town."region"
  AND city."countryId" = country."id"
  AND lower(city."name") = lower(town."name")
  AND city."regionId" IS NULL;

DROP TABLE "_RegionTown";
