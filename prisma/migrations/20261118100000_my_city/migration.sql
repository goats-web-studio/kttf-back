-- Мой город — ADR-093.

-- Центр города: по нему браузер находит ближайший к человеку город.
ALTER TABLE "City" ADD COLUMN "lat" DOUBLE PRECISION, ADD COLUMN "lng" DOUBLE PRECISION;

-- Города Казахстана из стартового справочника. Остальные администратор
-- заполнит в «Местах»; город без координат выбирается только руками.
UPDATE "City" c
SET "lat" = v.lat, "lng" = v.lng
FROM (VALUES
  ('Актау', 43.6481, 51.1722),
  ('Актобе', 50.2839, 57.167),
  ('Алматы', 43.2389, 76.8897),
  ('Астана', 51.1694, 71.4491),
  ('Атырау', 47.0945, 51.9238),
  ('Жезказган', 47.7833, 67.7144),
  ('Караганда', 49.8047, 73.1094),
  ('Кокшетау', 53.2833, 69.3833),
  ('Конаев', 43.8667, 77.0667),
  ('Костанай', 53.2144, 63.6246),
  ('Кызылорда', 44.8488, 65.4823),
  ('Павлодар', 52.2873, 76.9674),
  ('Петропавловск', 54.8728, 69.143),
  ('Семей', 50.4111, 80.2275),
  ('Талдыкорган', 45.0156, 78.3739),
  ('Тараз', 42.9, 71.3667),
  ('Туркестан', 43.2973, 68.2518),
  ('Уральск', 51.2333, 51.3667),
  ('Усть-Каменогорск', 49.9483, 82.6279),
  ('Шымкент', 42.3417, 69.5901)
) AS v(name, lat, lng), "Country" co
WHERE c."name" = v.name AND co."id" = c."countryId" AND co."code" = 'KZ';

-- Город аккаунта: что сайт показывает по умолчанию.
ALTER TABLE "User" ADD COLUMN "cityId" TEXT;
ALTER TABLE "User" ADD CONSTRAINT "User_cityId_fkey" FOREIGN KEY ("cityId") REFERENCES "City"("id") ON DELETE SET NULL ON UPDATE CASCADE;

-- Тем, у кого есть анкета, — город анкеты.
UPDATE "User" u SET "cityId" = p."cityId" FROM "Player" p WHERE p."userId" = u."id";
