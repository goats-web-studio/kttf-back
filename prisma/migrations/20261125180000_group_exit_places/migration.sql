-- ADR-125: не вышедшие из групп делят места по месту в группе — в схемах
-- «группы + сетка» и «группы + финальные группы».
-- Места завершённых турниров записаны в заявки (ADR-048) по прежнему
-- правилу — у не вышедших там пусто. Сброс отметки заставляет
-- `ensurePlaces` пересчитать их при первом обращении. Рейтинг не трогается:
-- бонус призёрам (ADR-069) только за места 1–3.
UPDATE "Tournament"
SET "placesAt" = NULL
WHERE "status" IN ('FINISHED', 'RATED')
  AND "formatConfig"->>'type' IN ('GROUPS_KNOCKOUT', 'GROUPS_FINAL_GROUPS');
