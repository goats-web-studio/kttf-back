/**
 * Время жизни access-токена. В документах не задано — выбрано здесь.
 *
 * Короткий срок нужен потому, что отзыва у JWT нет: выданный токен действует
 * до истечения, что бы ни случилось с сессией. Пятнадцать минут — граница,
 * за которой отозванная сессия перестаёт быть опасной, а обновление ещё не
 * происходит на каждом втором запросе.
 */
export const ACCESS_TOKEN_TTL_SECONDS = 15 * 60;

/** Время жизни сессии. ТЗ 2.1: «сессия живёт 90 дней, продлевается при активности». */
export const SESSION_TTL_MS = 90 * 24 * 60 * 60 * 1000;
