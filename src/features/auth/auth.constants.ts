/**
 * Константы аутентификации.
 *
 * Собраны в одном файле, потому что часть из них задана документами, а часть
 * выбрана при реализации. Источник у каждой подписан: без этого через месяц
 * не отличить требование от догадки.
 */

/** Длина одноразового кода. Шесть цифр — практика рынка, в документах не задана. */
export const CODE_LENGTH = 6;

/** Время жизни кода. ТС 8.3: «коды по SMS живут 5 минут». */
export const CODE_TTL_MS = 5 * 60 * 1000;

/** Запросов кода на телефон в час. ТС 8.3. */
export const CODE_REQUESTS_PER_HOUR = 5;

/** Окно, в котором считается лимит запросов. ТС 8.3. */
export const CODE_RATE_WINDOW_MS = 60 * 60 * 1000;

/**
 * Попыток ввода на один код. В документах не задано — выбрано здесь.
 *
 * Шестизначный код за 5 минут перебирается только при неограниченных попытках:
 * миллион вариантов против пяти попыток означает вероятность угадать 5 на
 * миллион. Без ограничения код перестаёт быть секретом.
 */
export const CODE_MAX_ATTEMPTS = 5;

/**
 * Время жизни access-токена. В документах не задано — выбрано здесь.
 *
 * Короткий срок нужен потому, что отзыва у JWT нет: выданный токен действует
 * до истечения, что бы ни случилось с сессией. Пятнадцать минут — граница,
 * за которой отозванная сессия перестаёт быть опасной, а обновление ещё не
 * происходит на каждом втором запросе.
 */
export const ACCESS_TOKEN_TTL_SECONDS = 15 * 60;

/** Время жизни сессии. ТЗ 2.1: «сессия живёт 90 дней, продлевается при активности». */
export const SESSION_TTL_MS = 90 * 24 * 60 * 60 * 1000;

/**
 * Телефон в E.164, казахстанский формат.
 *
 * Формат задан комментарием к полю `User.phone` в схеме: `+7XXXXXXXXXX`.
 * Единственный формат хранения — иначе один и тот же человек заводит два
 * аккаунта, написав номер по-разному, а ТЗ 2.1 требует «один телефон = один
 * аккаунт».
 */
export const PHONE_PATTERN = /^\+7\d{10}$/;
